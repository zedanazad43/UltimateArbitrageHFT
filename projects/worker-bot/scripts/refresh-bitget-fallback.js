#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';

const OUTPUT_PATH = new URL('../src/data/bitget-symbols-fallback.js', import.meta.url);
const REQUEST_TIMEOUT_MS = 15000;
const SOURCES = [
  'https://api.bitget.com/api/v2/spot/public/symbols',
  'https://capi.bitget.com/api/v2/spot/public/symbols',
];

function isLikelyTradeableUsdtSymbol(value) {
  if (typeof value !== 'string') return false;
  if (!value.endsWith('USDT')) return false;
  const base = value.slice(0, -4);
  if (!base) return false;
  return /^[A-Z0-9]{2,15}$/.test(base);
}

function normalizeBitgetRows(rows) {
  return (rows || [])
    .filter((row) => {
      const symbol = String(row?.symbol || '').toUpperCase();
      const quote = String(row?.quoteCoin || '').toUpperCase();
      const status = String(row?.status || '').toLowerCase();
      const enabled = String(row?.enableStatus || '').toLowerCase();
      const listed = status.includes('online') || status.includes('normal') || status.includes('trading') || enabled.includes('online');
      return (quote === 'USDT' || symbol.endsWith('USDT')) && listed;
    })
    .map((row) => String(row?.symbol || '').toUpperCase())
    .filter(isLikelyTradeableUsdtSymbol);
}

async function fetchJsonWithTimeout(url, timeoutMs) {
  const controller = new globalThis.AbortController();
  const timeout = globalThis.setTimeout(() => controller.abort(), timeoutMs);
  try {
    const response = await fetch(url, {
      signal: controller.signal,
      headers: {
        Accept: 'application/json',
        'Accept-Language': 'en-US,en;q=0.9',
        Referer: 'https://www.bitget.com/',
      },
    });

    if (!response.ok) {
      throw new Error(`HTTP ${response.status}`);
    }

    return response.json();
  } finally {
    globalThis.clearTimeout(timeout);
  }
}

async function getBitgetSymbols() {
  for (const url of SOURCES) {
    try {
      const payload = await fetchJsonWithTimeout(url, REQUEST_TIMEOUT_MS);
      const symbols = normalizeBitgetRows(payload?.data);
      if (symbols.length > 0) {
        return [...new Set(symbols)].sort((a, b) => a.localeCompare(b));
      }
    } catch (error) {
      console.warn(`[refresh-bitget-fallback] source failed: ${url} :: ${error.message}`);
    }
  }

  return [];
}

function renderModule(symbols) {
  const generatedAt = new Date().toISOString();
  const arrayLiteral = JSON.stringify(symbols);
  return `// Auto-generated by scripts/refresh-bitget-fallback.js\n// Generated at: ${generatedAt}\n\nexport const BITGET_SPOT_SYMBOLS_FALLBACK = ${arrayLiteral};\n`;
}

async function readExistingFile() {
  try {
    return await readFile(OUTPUT_PATH, 'utf8');
  } catch {
    return '';
  }
}

async function main() {
  const symbols = await getBitgetSymbols();
  if (symbols.length === 0) {
    throw new Error('No Bitget symbols discovered from all sources.');
  }

  const nextContent = renderModule(symbols);
  const previousContent = await readExistingFile();

  if (previousContent === nextContent) {
    console.log(`[refresh-bitget-fallback] no changes (${symbols.length} symbols)`);
    return;
  }

  await writeFile(OUTPUT_PATH, nextContent, 'utf8');
  console.log(`[refresh-bitget-fallback] updated ${OUTPUT_PATH.pathname} with ${symbols.length} symbols`);
}

main().catch((error) => {
  console.error(`[refresh-bitget-fallback] failed: ${error.message}`);
  process.exitCode = 1;
});
